// Regenerates lib/product-images.ts from the files in public/products.
// `<slug>.<ext>` is the main photo, `<slug>-2.<ext>`, `-3`… are extra angles.
// Run after adding or replacing product photos: node scripts/gen-product-images.mjs
import fs from "node:fs";
import path from "node:path";

const dir = path.join(import.meta.dirname, "..", "public", "products");
const files = fs.readdirSync(dir).filter((f) => /\.(jpe?g|png|webp|avif)$/i.test(f)).sort();

// A trailing "-2".."-9" is an extra angle only when the main photo exists too,
// so slugs that end in a number ("…-ddr5-32-6000", "…-360") stay whole.
const bases = new Set(files.map((f) => f.replace(/\.[^.]+$/, "")));
const map = {};
for (const f of files) {
  const base = f.replace(/\.[^.]+$/, "");
  const m = base.match(/^(.*)-([2-9])$/);
  const isAngle = m && bases.has(m[1]);
  const slug = isAngle ? m[1] : base;
  const order = isAngle ? Number(m[2]) : 1;
  (map[slug] ??= []).push({ order, src: `/products/${f}` });
}

const entries = Object.keys(map)
  .sort()
  .map((slug) => {
    const srcs = map[slug].sort((a, b) => a.order - b.order).map((x) => JSON.stringify(x.src));
    return `  ${JSON.stringify(slug)}: [${srcs.join(", ")}],`;
  });

const out = `// Generated by scripts/gen-product-images.mjs from public/products. Do not edit.
export const PRODUCT_IMAGES: Record<string, string[]> = {
${entries.join("\n")}
};
`;
fs.writeFileSync(path.join(import.meta.dirname, "..", "lib", "product-images.ts"), out);
console.log(`${Object.keys(map).length} products, ${files.length} photos`);
